# индексы в итоговой таблице: А-Я = 0..31, а-я = 32..63, Ё = 64, ё = 65
UPPER = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
LOWER = "абвгдежзийклмнопрстуфхцчшщъыьэюя"

# буквы, чьи формы берём из font8x8 (латиница)
REUSE = {'А':'A','В':'B','Е':'E','К':'K','М':'M','Н':'H','О':'O','Р':'P','С':'C','Т':'T','Х':'X',
         'а':'a','е':'e','о':'o','с':'c','у':'y','х':'x','р':'p','к':'k','У':'Y'}

def latin_with_dots(ch):
    """'Ё'/'ё' = E/e с двумя точками сверху."""
    src = base[ord('E')] if ch.isupper() else base[ord('e')]
    g = list(src)
    g[0] = 0b00100100
    if g[1] == 0:
        g[1] = 0
    return g

table = []
for ch in UPPER + LOWER:
    if ch in REUSE:
        table.append((ch, base[ord(REUSE[ch])]))
    else:
        table.append((ch, rows2bytes(DESIGN[ch])))
table.append(('Ё', latin_with_dots('Ё')))
table.append(('ё', latin_with_dots('ё')))

assert len(table) == 66

# --- визуальная проверка ---
mode = sys.argv[1] if len(sys.argv) > 1 else "art"
if mode == "art":
    for name, g in table:
        print(f"--- {name} ---")
        print(art(g))
        print()
else:
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("/* font8x8_cyr — кириллические глифы 8x8 для AresOS (генерируется tools/cyrfont_gen.py).\n")
