# начертанию с латинскими, берутся из font8x8.h; уникальные рисуются вручную
# ниже (строки '#'/'.' = пиксели слева направо, bit0 = левый столбец).
import re, sys

SRC = "/home/user/AresOS/kernel/drivers/font8x8.h"

def load_font8x8(path):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r"font8x8_basic\[128\]\[8\] = \{(.*?)\};", txt, re.S)
    body = m.group(1)
    glyphs = re.findall(r"\{\s*(0x[0-9A-Fa-f]{2}(?:,\s*0x[0-9A-Fa-f]{2}){7})\s*}", body)
    return [[int(v, 16) for v in g.split(",")] for g in glyphs]

base = load_font8x8(SRC)

def rows2bytes(rows):
    out = []
    for r in rows:
        v = 0
        for i, ch in enumerate(r):
            if ch == '#':
                v |= (1 << i)
        out.append(v)
    return out

def art(b):
    return "\n".join("".join('#' if (row >> x) & 1 else '.' for x in range(8)) for row in b)

